// Admission decides whether a candidate may be validated or published. It sees
// model output only as data and fails closed on anything it cannot prove.
import { matchesAny } from "../../review-gate/src/glob.mjs";
import { assertPath, assertText } from "./digest.mjs";
import { contractViolations, dockerFroms, droppedTargets, isDockerfile } from "./contract.mjs";

const DEP_GROUPS = ["dependencies", "devDependencies", "optionalDependencies", "peerDependencies"];
const VERSION = /^(?:[~^]|>=?|<=?|=)?v?\d+(?:\.\d+){0,2}(?:-[0-9A-Za-z.-]+)?(?:\s*(?:\|\||<|<=|>=?)\s*v?\d+(?:\.\d+){0,2}(?:-[0-9A-Za-z.-]+)?)*$|^(?:\d+|\*)\.x$|^workspace:[*^~]?$|^catalog:[\w-]*$/;

export function validateProposalShape(value, { maxFiles, maxBytes }) {
  if (!value || typeof value !== "object" || Array.isArray(value) || Object.keys(value).join() !== "files" || !Array.isArray(value.files)) {
    throw new Error('repair proposal must be exactly {"files":[...]}');
  }
  if (value.files.length > maxFiles) throw new Error(`repair proposal has more than ${maxFiles} files`);
  const seen = new Set();
  let total = 0;
  for (const f of value.files) {
    if (!f || typeof f !== "object" || Object.keys(f).sort().join() !== "content,path") throw new Error("each proposed file is exactly {path, content}");
    assertPath(f.path);
    assertText(f.content, maxBytes, `proposed ${f.path}`);
    if (seen.has(f.path)) throw new Error(`duplicate proposed path ${f.path}`);
    seen.add(f.path);
    total += Buffer.byteLength(f.content);
  }
  if (total > maxBytes) throw new Error(`repair proposal exceeds ${maxBytes} bytes`);
  return value.files;
}

function manifestChangeOk(before, after) {
  let a;
  let b;
  try {
    a = JSON.parse(before);
    b = JSON.parse(after);
  } catch {
    return "package.json is not valid JSON";
  }
  const strip = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => !DEP_GROUPS.includes(k)));
  if (JSON.stringify(strip(a)) !== JSON.stringify(strip(b))) return "only dependency versions may change in package.json";
  for (const g of DEP_GROUPS) {
    const x = a[g] ?? {};
    const y = b[g] ?? {};
    if (Object.keys(x).sort().join() !== Object.keys(y).sort().join()) return `dependencies cannot be added or removed (${g})`;
    for (const [name, v] of Object.entries(y)) {
      if (typeof v !== "string" || (v !== x[name] && !VERSION.test(v))) return `${g}.${name} must stay a registry version`;
    }
  }
  return null;
}

// head: Map(path -> content|null) at the target head for every path involved.
// synced: Map(path -> content) written by the trusted runtime-contract sync.
// proposal: [{path, content}] from the model (may be empty for a sync-only task).
// generated: Map(path -> content) produced by the trusted lockfile command.
// fieldFiles: Map(path -> content) of every file a runtime field addresses.
export function admit({ policy, head, synced = new Map(), proposal = [], generated = new Map(), generatedPaths = [], targets = [], moves = [], fieldFiles = new Map() }) {
  const reasons = [];
  const final = new Map();
  for (const [p, c] of synced) final.set(p, c);
  for (const f of proposal) {
    const p = f.path;
    if (generatedPaths.includes(p)) { reasons.push(`${p} is generated by the validator; the model may not edit it`); continue; }
    if (matchesAny(p, policy.repair.protected)) { reasons.push(`${p} is protected`); continue; }
    if (!matchesAny(p, policy.repair.editable)) { reasons.push(`${p} is outside the editable paths`); continue; }
    const before = synced.get(p) ?? head.get(p);
    if (/(^|\/)package\.json$/.test(p)) {
      if (typeof before !== "string") { reasons.push(`${p} cannot be created`); continue; }
      const why = manifestChangeOk(before, f.content);
      if (why) { reasons.push(`${p}: ${why}`); continue; }
    }
    if (isDockerfile(p)) {
      const was = dockerFroms(before ?? "").map((x) => x.text.trim());
      const now = dockerFroms(f.content).map((x) => x.text.trim());
      const anyFrom = f.content.split("\n").filter((l) => /^\s*FROM\s/i.test(l)).length;
      if (was.join("\n") !== now.join("\n") || anyFrom !== now.length) { reasons.push(`${p}: FROM lines are immutable image identities`); continue; }
    }
    final.set(p, f.content);
  }
  for (const [p, c] of generated) {
    if (!generatedPaths.includes(p)) reasons.push(`${p} is not a generated path`);
    else final.set(p, c);
  }
  for (const [p, c] of [...final]) if (head.get(p) === c) final.delete(p);

  if (final.size > policy.repair.maxFiles + generatedPaths.length) reasons.push(`candidate changes more than ${policy.repair.maxFiles} files`);
  const view = new Map([...head, ...final]);
  for (const t of droppedTargets(targets, view)) reasons.push(`candidate drops the requested ${t.kind} target ${t.key} -> ${t.value} in ${t.path}`);
  const fields = new Map(fieldFiles);
  for (const [p, c] of final) if (fields.has(p)) fields.set(p, c);
  for (const v of contractViolations(policy, moves, fields)) reasons.push(`runtime contract: ${v}`);
  return { ok: reasons.length === 0, reasons, files: [...final].map(([path, content]) => ({ path, content })).sort((a, b) => a.path.localeCompare(b.path)) };
}
